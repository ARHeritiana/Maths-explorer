#!/usr/bin/env python3
"""Data of two curiosities: Gerver's sofa (site/js/gallery-sofa-gerver.js) and the best known packings of unit squares
(site/js/gallery-squares-data.js). Run by hand; needs numpy, scipy, shapely and pyyaml.

  python3 scripts/build-gallery-data.py sofa
  python3 scripts/build-gallery-data.py squares /path/to/checkout/of/github.com/jlevy/squares

Gerver's sofa follows the definition formalised in github.com/vltanh/lean4-moving-sofa (MovingSofaBridge/Defs.lean,
after D. Romik, "Differential equations and exact solutions in the moving sofa problem", 2018): the constants
A, B, phi, theta solve Romik's equations (1) to (4); the rotation path p(alpha) is built from r(alpha) by two integrals;
the sofa is the horizontal side of the hallway intersected with every hallway translated by p(alpha) then turned by
alpha, and with the turned vertical side at alpha = pi/2. The intersection is taken over N angles; the corner of the
hallway traces the notch, so the thin wedges it leaves between two angles are removed as well. The area is checked
against Gerver's constant 2.21953166...

The packings are the known-best witnesses of the squares project (Joshua Levy, CC BY 4.0), n = 1 to 28, with the
bounds and credits of its atlas (packing/atlas/known-best/bound-citations.json).
"""
import json, math, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GERVER_CONSTANT = 2.21953166887197  # Romik 2018, the area of Gerver's sofa


def sofa(N=1000):
    import numpy as np
    from math import pi, sin, cos
    from scipy.optimize import fsolve
    from scipy.integrate import quad
    from shapely.geometry import Polygon, box
    from shapely.ops import unary_union
    from shapely import affinity

    def eqs(v):
        A, B, f, t = v
        return [A * (cos(t) - cos(f)) - 2 * B * sin(f) + (t - f - 1) * cos(t) - sin(t) + cos(f) + sin(f),
                A * (3 * sin(t) + sin(f)) - 2 * B * cos(f) + 3 * (t - f - 1) * sin(t) + 3 * cos(t) - sin(f) + cos(f),
                A * cos(f) - (sin(f) + 0.5 - cos(f) / 2 + B * sin(f)),
                (A + pi / 2 - f - t) - (B - (t - f) * (1 + A) / 2 - (t - f) ** 2 / 4)]
    A, B, PHI, TH = fsolve(eqs, [0.09, 1.4, 0.039, 0.68], xtol=1e-15)
    assert max(abs(e) for e in eqs([A, B, PHI, TH])) < 1e-12 and 0.039 <= PHI <= 0.04 and 0.68 <= TH <= 0.69

    def r(a):
        if a <= PHI: return 0.5
        if a <= TH: return (1 + A + a - PHI) / 2
        if a <= pi / 2 - TH: return A + a - PHI
        if a <= pi / 2 - PHI: return B - (pi / 2 - a - PHI) * (1 + A) / 2 - (pi / 2 - a - PHI) ** 2 / 4
        return 0.0
    breaks = [PHI, TH, pi / 2 - TH, pi / 2 - PHI]
    def integral(fn, a, b):
        pts = [x for x in breaks if min(a, b) < x < max(a, b)]
        return quad(fn, a, b, points=pts or None, limit=200, epsabs=1e-13, epsrel=1e-13)[0]
    y = lambda a: integral(lambda t: r(t) * sin(t), a, pi / 2 - PHI)
    x = lambda a: 1 - integral(lambda t: r(t) * cos(t), a, pi / 2 - PHI)
    x0 = x(0)
    def p(a):
        px = cos(a) - 1 if a <= PHI else x(pi / 2 - a) * cos(a) + y(pi / 2 - a) * sin(a) - 1
        py = y(a) * cos(a) - (4 * x0 - 2 - x(a)) * sin(a) - 1 if a <= pi / 2 - PHI else -(4 * x0 - 3) * sin(a) - 1
        return np.array([px, py])

    BIG = 12
    H, V = box(-BIG, 0, 1, 1), box(0, -BIG, 1, 1)
    L = H.union(V)
    img = lambda region, a: affinity.rotate(affinity.translate(region, *p(a)), a, origin=(0, 0), use_radians=True)
    rot = lambda a, v: np.array([cos(a) * v[0] - sin(a) * v[1], sin(a) * v[0] + cos(a) * v[1]])
    angles = [pi / 2 * k / N for k in range(N + 1)]
    S = img(H, 0).intersection(img(V, pi / 2))
    for a in angles: S = S.intersection(img(L, a))
    corner = [rot(a, p(a)) for a in angles]
    wall = lambda a, c: c + 0.03 * rot(a, np.array([-1, -1]) / math.sqrt(2))
    wedges = unary_union([Polygon([corner[k], corner[k + 1], wall(angles[k + 1], corner[k + 1]), wall(angles[k], corner[k])]) for k in range(N)])
    S = S.difference(wedges)
    assert S.geom_type == "Polygon" and abs(S.area - GERVER_CONSTANT) < 1e-5, S.area
    Q = S.simplify(5e-6, preserve_topology=True)
    outline = [[round(u, 6), round(v, 6)] for u, v in list(Q.exterior.coords)[:-1]]
    path = [[round(a, 6), round(float(q[0]), 7), round(float(q[1]), 7)] for a in np.linspace(0, pi / 2, 361) for q in [p(a)]]
    data = {"A": A, "B": B, "phi": PHI, "theta": TH, "area": S.area, "outline": outline, "path": path}
    out = ROOT / "site/js/gallery-sofa-gerver.js"
    out.write_text("// GENERATED by scripts/build-gallery-data.py sofa: Gerver's sofa from Romik's equations (do not edit).\n"
                   "// outline: the sofa in the hallway frame at the start of the turn; path: [alpha, p(alpha)] every quarter degree;\n"
                   "// at angle alpha the sofa point q is at R(-alpha) q - p(alpha).\n"
                   f"export const GERVER = {json.dumps(data, separators=(',', ':'))};\n")
    print(f"Gerver: A = {A:.15f}, B = {B:.15f}, phi = {PHI:.15f}, theta = {TH:.15f}, area {S.area:.7f}, {len(outline)} vertices -> {out}")


def squares(checkout):
    import yaml
    from fractions import Fraction
    base = Path(checkout) / "packing"
    num = lambda s: float(Fraction(s)) if "/" in str(s) else float(s)
    cites = {e["n"]: e for e in json.loads((base / "atlas/known-best/bound-citations.json").read_text())["citations"]["entries"]}
    out = {}
    for n in range(1, 29):
        w = yaml.safe_load((base / f"witnesses/known-best/n-{n:03d}.yaml").read_text())["witness"]
        sq = []
        for s in w["squares"]:
            if w["representation"] == "center-angle":
                assert w["coordinates"]["angle_unit"] == "degrees"
                sq.append([num(s["center"][0]), num(s["center"][1]), math.radians(num(s["angle"]))])
            else:
                c = [[num(u), num(v)] for u, v in s["corners"]]
                sq.append([sum(q[0] for q in c) / 4, sum(q[1] for q in c) / 4, math.atan2(c[1][1] - c[0][1], c[1][0] - c[0][0])])
        side, e = num(w["side"]), cites[n]
        lo, up = e["lower"] or {}, e["upper"] or {}
        k = round(math.sqrt(n))
        if k * k == n or n in (2, 3): status, ref = "proved", ""
        elif lo.get("value") and abs(float(lo["value"]) - side) < 1e-6: status, ref = ("claimed" if "2026" in lo.get("text", "") else "proved"), lo.get("text", "")
        else: status, ref = "open", ""
        by = up.get("text", "").replace("Squares in Squares", "").strip(", ")
        out[n] = {"side": side, "status": status, "ref": ref, "by": by, "squares": [[round(v, 12) for v in q] for q in sq]}
    target = ROOT / "site/js/gallery-squares-data.js"
    target.write_text("// GENERATED by scripts/build-gallery-data.py squares (do not edit). Best known packings of n unit squares, n = 1 to 28:\n"
                      "// squares [x, y, angle in radians] (centre, lower left origin); status: proved, claimed (announced in 2026, not\n"
                      "// published) or open. Source: Joshua Levy, the squares project (https://github.com/jlevy/squares), CC BY 4.0,\n"
                      "// known-best witnesses and atlas bound citations, with the credits of E. Friedman's Squares in Squares.\n"
                      f"export const PACKINGS = {json.dumps(out, separators=(',', ':'), ensure_ascii=False)};\n")
    print(f"squares: {len(out)} packings -> {target}")


if __name__ == "__main__":
    if sys.argv[1:2] == ["sofa"]: sofa()
    elif sys.argv[1:2] == ["squares"] and len(sys.argv) == 3: squares(sys.argv[2])
    else: sys.exit(__doc__)
