// Error coverage matrix: misconception x curriculum, from site/js/errors-data.js (built activities) and
// content/data/error-coverage.json (planned ones). Writes docs/ERROR_COVERAGE.md; `--check` only compares.
// A built activity covers a curriculum when one of its chapter links belongs to that course (chapter id prefix).
import { readFileSync, writeFileSync } from 'node:fs';
import { all } from '../site/js/errors-model.js';

const root = new URL('../', import.meta.url);
const data = JSON.parse(readFileSync(new URL('content/data/error-coverage.json', root), 'utf8'));

export function matrix() {
  const course = (hash) => (hash.match(/^#chapter\/([a-z]+)-/) || [])[1];
  const built = all().map((e) => ({
    id: e.id, title: e.title[0], topic: data.topicOverrides[e.id] || data.topicOfFamily[e.family], built: true,
    cells: Object.fromEntries(data.curricula.map((c) => [c.id, (e.links || []).filter((h) => course(h) === c.id).map((h) => h.split('/')[1])])),
  }));
  const planned = data.planned.map((p) => ({ id: p.id, title: p.title, topic: p.topic, built: false, cells: Object.fromEntries(data.curricula.map((c) => [c.id, p.curricula.includes(c.id)])) }));
  return { built, planned };
}

export function render() {
  const { built, planned } = matrix(), cur = data.curricula;
  const cell = (r, c) => r.built ? (r.cells[c.id].length ? r.cells[c.id].join(', ') : '·') : (r.cells[c.id] ? 'prévu' : '·');
  const out = [];
  out.push('# Error correction: coverage by curriculum and misconception', '',
    'Generated by `scripts/error-coverage.mjs` from `site/js/errors-data.js` and `content/data/error-coverage.json`. Do not edit by hand.', '',
    'A built activity is listed under every curriculum for which it links to a chapter (the chapter ids are shown). `prévu` marks a misconception expected in that curriculum with no activity yet. `·` means neither. **The placement of a misconception in an official programme is [VERIFY — check Eduscol]: this matrix is a working plan, not a statement about the programmes.** Coverage is judged by misconception and topic, not by the number of activities.', '');
  const total = built.length + planned.length;
  out.push(`Built: ${built.length}. Planned, not built: ${planned.length}. Built share of the listed misconceptions: ${Math.round(100 * built.length / total)} %.`, '');
  out.push('## Summary by topic', '', '| Topic | Built | Planned |', '|---|---:|---:|');
  for (const [id, label] of Object.entries(data.topics)) out.push(`| ${label} | ${built.filter((r) => r.topic === id).length} | ${planned.filter((r) => r.topic === id).length} |`);
  out.push('', '## Summary by curriculum', '', '| Curriculum | Built activities linked | Planned misconceptions |', '|---|---:|---:|');
  for (const c of cur) out.push(`| ${c.label} | ${built.filter((r) => r.cells[c.id].length).length} | ${planned.filter((r) => r.cells[c.id]).length} |`);
  for (const [id, label] of Object.entries(data.topics)) {
    const rows = [...built, ...planned].filter((r) => r.topic === id);
    if (!rows.length) continue;
    out.push('', `## ${label}`, '', `| Misconception | Status | ${cur.map((c) => c.label).join(' | ')} |`, `|---|---|${cur.map(() => '---').join('|')}|`);
    for (const r of rows) out.push(`| ${r.title} (\`${r.id}\`) | ${r.built ? 'built' : 'planned'} | ${cur.map((c) => cell(r, c)).join(' | ')} |`);
  }
  out.push('');
  return out.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const target = new URL('docs/ERROR_COVERAGE.md', root), text = render();
  if (process.argv.includes('--check')) { if (readFileSync(target, 'utf8') !== text) { console.error('docs/ERROR_COVERAGE.md is stale: run node scripts/error-coverage.mjs'); process.exit(1); } }
  else writeFileSync(target, text);
}
