"""Inventory the LaTeX trees: environments, macros, counters, colours, packages,
edition switches and entry files, per course. Writes docs/TEX_INVENTORY.md.

Usage: python3 scripts/tex-inventory.py [--json out.json]
Only French sources are scanned for definitions and usage counts (the -en twins
mirror them); twin parity is reported separately.
"""
import argparse, collections, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'content/latex'
OUT = ROOT / 'docs/TEX_INVENTORY.md'

DEF_PATTERNS = {
    'environment': [r'\\newenvironment\*?\{(\w+\*?)\}', r'\\renewenvironment\*?\{(\w+\*?)\}',
                    r'\\newtcolorbox(?:\[[^\]]*\])?\{(\w+\*?)\}', r'\\newtcbtheorem(?:\[[^\]]*\])?\{(\w+)\}',
                    r'\\DeclareTColorBox(?:\[[^\]]*\])?\{(\w+)\}', r'\\newmdenv(?:\[[^\]]*\])?\{(\w+)\}',
                    r'\\newtheorem\*?\{(\w+)\}', r'\\NewDocumentEnvironment\{(\w+)\}', r'\\newmdtheoremenv(?:\[[^\]]*\])?\{(\w+)\}'],
    'macro': [r'\\(?:re)?newcommand\*?\{?\\(\w+)\}?', r'\\providecommand\*?\{?\\(\w+)\}?', r'\\def\\(\w+)',
              r'\\DeclareMathOperator\*?\{?\\(\w+)\}?', r'\\NewDocumentCommand\{?\\(\w+)\}?', r'\\let\\(\w+)'],
    'counter': [r'\\newcounter\{(\w+)\}'],
    'colour': [r'\\definecolor\{([\w-]+)\}', r'\\colorlet\{([\w-]+)\}'],
    'if': [r'\\newif\\if(\w+)'],
}
PKG = re.compile(r'\\(?:usepackage|RequirePackage)(?:\[[^\]]*\])?\{([^}]+)\}')
BEGIN = re.compile(r'\\begin\{(\w+\*?)\}')
CLEARPAGE = re.compile(r'\\(?:clearpage|newpage|pagebreak)\b')
RAWRGB = re.compile(r'\\definecolor\{[^}]+\}\{(?:RGB|rgb|HTML)\}')
# Standard environments that are not part of a course vocabulary.
STD = set('document itemize enumerate description center tabular tabularx array align align* aligned equation equation* '
          'tikzpicture axis scope minipage cases pmatrix bmatrix matrix gather gather* figure table multicols multicols* '
          'flushleft flushright quote lstlisting verbatim split alignat alignat* longtable small footnotesize '
          'otherlanguage tcolorbox mdframed minted subfigure wrapfigure adjustbox tikzcd forest groupplot '
          'vmatrix smallmatrix eqnarray displaymath math tabbing quotation verse thebibliography abstract '
          'dcases tblr NiceTabular tabular* varwidth comment frame'.split())


def course_of(p):
    return p.relative_to(SRC).parts[0]


def is_en(p):
    return p.stem.endswith('-en') or '-en.' in p.name


def strip_comments(text):
    return re.sub(r'(?<!\\)%.*', '', text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--json')
    args = ap.parse_args()
    files = sorted(p for p in SRC.rglob('*') if p.suffix in ('.tex', '.sty'))
    courses = sorted({course_of(p) for p in files})
    defs = {k: collections.defaultdict(lambda: collections.defaultdict(list)) for k in DEF_PATTERNS}
    pkgs = collections.defaultdict(set)
    uses = collections.defaultdict(collections.Counter)
    bodies = []
    stats = collections.defaultdict(lambda: {'files': 0, 'en': 0, 'lines': 0, 'clearpage': 0, 'rawrgb': 0})
    for p in files:
        c = course_of(p)
        text = p.read_text(encoding='utf-8', errors='replace')
        s = stats[c]
        s['files'] += 1
        s['lines'] += text.count('\n')
        if is_en(p):
            s['en'] += 1
            continue
        body = strip_comments(text)
        s['clearpage'] += len(CLEARPAGE.findall(body))
        s['rawrgb'] += len(RAWRGB.findall(body))
        rel = str(p.relative_to(SRC))
        for kind, pats in DEF_PATTERNS.items():
            for pat in pats:
                for name in re.findall(pat, body):
                    defs[kind][name][c].append(rel)
        for m in PKG.findall(body):
            for name in m.split(','):
                pkgs[name.strip()].add(c)
        for env in BEGIN.findall(body):
            uses[env][c] += 1
        bodies.append((c, body))

    # Usage of every defined macro (box commands such as \\exemple{} are content vocabulary too).
    muses = collections.defaultdict(collections.Counter)
    for c, body in bodies:
        for name in re.findall(r'\\([A-Za-z]+)', body):
            if name in defs['macro']:
                muses[name][c] += 1

    # Entry files: anything with \documentclass.
    entries = collections.defaultdict(list)
    for p in files:
        if '\\documentclass' in p.read_text(encoding='utf-8', errors='replace'):
            entries[course_of(p)].append(str(p.relative_to(SRC)))

    custom_envs = {e for e in uses if e not in STD} | set(defs['environment'])
    lines = ['# TeX inventory', '',
             'Generated by `python3 scripts/tex-inventory.py`; do not edit by hand. Definitions and usage counts are from the',
             'French files (`-en` twins mirror them). "Defined in" lists the courses whose sources define the name.', '',
             '## Per course', '',
             '| Course | Files | of which `-en` | Lines | `\\clearpage`/`\\newpage` (FR) | raw `\\definecolor` (FR) | Entry files (FR+EN) |',
             '|---|---:|---:|---:|---:|---:|---|']
    for c in courses:
        s = stats[c]
        lines.append(f"| {c} | {s['files']} | {s['en']} | {s['lines']} | {s['clearpage']} | {s['rawrgb']} | {len(entries[c])}: "
                     + ', '.join(f'`{e}`' for e in sorted(entries[c]) if not e.endswith('-en.tex')) + ' |')
    tot = {k: sum(stats[c][k] for c in courses) for k in ('files', 'en', 'lines')}
    lines.append(f"| **total** | {tot['files']} | {tot['en']} | {tot['lines']} | | | |")

    lines += ['', '## Course environments (defined or used, standard LaTeX ones excluded)', '',
              '| Environment | ' + ' | '.join(courses) + ' | Defined in |', '|---|' + '---:|' * len(courses) + '---|']
    for env in sorted(custom_envs, key=lambda e: (-sum(uses[e].values()), e)):
        row = [str(uses[env].get(c, '')) for c in courses]
        where = ', '.join(sorted(defs['environment'].get(env, {}))) or '(package)'
        lines.append(f'| `{env}` | ' + ' | '.join(row) + f' | {where} |')

    for kind, title in (('macro', 'Macros'), ('counter', 'Counters'), ('colour', 'Colours'), ('if', 'Conditionals (`\\newif`)')):
        lines += ['', f'## {title}', '', '| Name | Courses | Definitions | Uses (FR, incl. definition) |', '|---|---|---:|---:|']
        for name in sorted(defs[kind], key=str.lower):
            where = defs[kind][name]
            n = sum(len(v) for v in where.values())
            u = sum(muses[name].values()) if kind == 'macro' else ''
            lines.append(f"| `{name}` | {', '.join(sorted(where))} | {n} | {u} |")
        multi = [n for n, w in defs[kind].items() if len(w) > 1]
        lines.append('')
        lines.append(f'{len(defs[kind])} names; {len(multi)} defined in more than one course.')

    lines += ['', '## Packages', '', '| Package | Courses |', '|---|---|']
    for name in sorted(pkgs, key=str.lower):
        lines.append(f"| `{name}` | {', '.join(sorted(pkgs[name]))} |")
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    if args.json:
        Path(args.json).write_text(json.dumps({k: {n: dict(w) for n, w in v.items()} for k, v in defs.items()}, indent=1))
    print(f'wrote {OUT.relative_to(ROOT)}: {tot["files"]} files, {len(custom_envs)} course environments, '
          f'{len(defs["macro"])} macros, {len(defs["counter"])} counters, {len(defs["colour"])} colours, {len(pkgs)} packages')


if __name__ == '__main__':
    main()
