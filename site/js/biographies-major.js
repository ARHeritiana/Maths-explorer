      "Sa Mécanique analytique (1788) exprime les problèmes de mouvement à l’aide de principes variationnels et d’équations, en réduisant le recours aux constructions géométriques. Il contribue au calcul des variations, à l’étude des équations différentielles et à la stabilité des systèmes mécaniques. En algèbre, ses réflexions sur les permutations des racines préparent les idées qui se développeront avec Ruffini, Abel et Galois. Son théorème des quatre carrés est une étape marquante de la théorie des nombres. Il travaille également à l’interpolation et à l’approximation. Lagrange se distingue par une recherche systématique de principes généraux capables d’unifier des problèmes apparemment différents.",
