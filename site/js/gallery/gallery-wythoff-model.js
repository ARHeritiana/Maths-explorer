// The snub: rotations only; the distances are found so that every edge has the same length (Nelder-Mead on the simplex).
const snubCache = new Map();
export function snubPoint(id) {
  if (snubCache.has(id)) return snubCache.get(id);
  const spread = (x) => { const d = [Math.abs(x[0]), Math.abs(x[1]), 1]; const L = edgeLengths(wythoff(id, d, true)); const m = L.reduce((s, v) => s + v, 0) / L.length; return L.reduce((s, v) => s + (v - m) ** 2, 0) / (m * m); };
  let pts = [[1, 1], [1.3, 1], [1, 1.3]].map((x) => ({ x, f: spread(x) }));
  for (let it = 0; it < 300; it++) {
    pts.sort((a, b) => a.f - b.f); const [b, g, w] = pts, c = [(b.x[0] + g.x[0]) / 2, (b.x[1] + g.x[1]) / 2], at = (k) => { const x = [c[0] + k * (w.x[0] - c[0]), c[1] + k * (w.x[1] - c[1])]; return { x, f: spread(x) }; };
    const r = at(-1); if (r.f < b.f) { const e = at(-2); pts[2] = e.f < r.f ? e : r; } else if (r.f < g.f) pts[2] = r; else { const k = at(0.5); if (k.f < w.f) pts[2] = k; else pts = [b, ...[g, w].map((q) => { const x = [(b.x[0] + q.x[0]) / 2, (b.x[1] + q.x[1]) / 2]; return { x, f: spread(x) }; })]; }
    if (Math.abs(pts[0].f - pts[2].f) < 1e-28) break;
  }
  pts.sort((a, b) => a.f - b.f); const d = [Math.abs(pts[0].x[0]), Math.abs(pts[0].x[1]), 1];
  snubCache.set(id, d); return d;
}

// The dual, by polar reciprocity about the sphere through the edge midpoints: a vertex for each face, a face for each vertex.
export function dual(S) {
  const mids = S.edges.map(([a, b]) => norm(scale(add(S.verts[a], S.verts[b]), 0.5))), rho2 = (mids.reduce((s, v) => s + v, 0) / mids.length) ** 2;
  const verts = S.faces.map((f) => scale(f.normal, rho2 / f.d));
  const faces = S.verts.map((v, k) => {
    const around = S.faces.map((f, i) => [f, i]).filter(([f]) => f.verts.includes(k)).map(([, i]) => i), n = unit(v), c = scale(around.reduce((s, i) => add(s, verts[i]), [0, 0, 0]), 1 / around.length);
    const u = unit(sub(verts[around[0]], c)), w = cross(n, u), ang = (i) => Math.atan2(dot(sub(verts[i], c), w), dot(sub(verts[i], c), u));
    return { verts: around.sort((a, b) => ang(a) - ang(b)), normal: n, d: dot(n, verts[around[0]]) };
  });
  return finish(verts, faces);
}

// Classification from computed properties only.
export const isConvex = (S) => S.faces.every((f) => S.verts.every((v) => dot(f.normal, v) <= f.d + 1e-7));
export function regularFace(S, f, tol = 1e-6) {
  const P = f.verts.map((k) => S.verts[k]), n = P.length, L = P.map((p, i) => norm(sub(P[(i + 1) % n], p)));
  const ang = P.map((p, i) => { const a = sub(P[(i - 1 + n) % n], p), b = sub(P[(i + 1) % n], p); return Math.acos(Math.max(-1, Math.min(1, dot(a, b) / (norm(a) * norm(b))))); });
  return Math.max(...L) - Math.min(...L) < tol * L[0] && Math.max(...ang) - Math.min(...ang) < tol;
}
// The vertex configuration: the sizes of the faces round a vertex, in order, read the same up to rotation and reflection.
export function vertexConfig(S, k) {
  const around = S.faces.filter((f) => f.verts.includes(k)), n = S.verts[k];
  const c = around.map((f) => f.verts.reduce((s, q) => add(s, S.verts[q]), [0, 0, 0]).map((x) => x / f.verts.length));
  const u = unit(sub(c[0], scale(n, dot(c[0], n) / dot(n, n)))), w = cross(unit(n), u);
  const order = around.map((f, i) => [f.verts.length, Math.atan2(dot(c[i], w), dot(c[i], u))]).sort((a, b) => a[1] - b[1]).map((x) => x[0]);
  const forms = []; for (const seq of [order, [...order].reverse()]) for (let r = 0; r < seq.length; r++) forms.push([...seq.slice(r), ...seq.slice(0, r)]);
  const less = (x, y) => { for (let i = 0; i < x.length; i++) if (x[i] !== y[i]) return x[i] - y[i]; return 0; };
  return forms.sort(less)[0].join('.');   // the smallest reading, compared as numbers
}
export function faceShape(S, f) {   // sorted side lengths and angles: two congruent faces have the same shape
  const P = f.verts.map((k) => S.verts[k]), n = P.length, L = P.map((p, i) => norm(sub(P[(i + 1) % n], p))).sort((a, b) => a - b);
  return L.map((x) => (x / L.at(-1)).toFixed(5)).join(',') + '/' + n;
}
export function classify(S) {
  const convex = isConvex(S), regular = S.faces.every((f) => regularFace(S, f)), configs = new Set(S.verts.map((_, k) => vertexConfig(S, k))), sameVertices = configs.size === 1;
  const shapes = new Set(S.faces.map((f) => faceShape(S, f))), oneFace = shapes.size === 1, sizes = [...new Set(S.faces.map((f) => f.verts.length))];
  let kind;
  if (convex && regular && sameVertices && oneFace) kind = 'platonic';
  else if (convex && regular && sameVertices) {
    const c = S.faces.reduce((m, f) => (m[f.verts.length] = (m[f.verts.length] || 0) + 1, m), {}), big = sizes.filter((s) => c[s] === 2);
    kind = big.length && sizes.every((s) => s === big[0] || s === 4 || s === 3) && (c[4] === big[0] || c[3] === 2 * big[0]) ? 'prism' : 'archimedean';
  } else if (convex && regular) kind = 'johnson';
  else if (convex && oneFace) kind = 'catalan';
  else kind = 'other';
  return { convex, regular, sameVertices, oneFace, configs: [...configs], kind };
}
// Solids of the classification game that are not in the triangle: prisms, antiprisms and three Johnson solids.
export function prism(n) { const r = 1 / (2 * Math.sin(Math.PI / n)), P = []; for (const z of [-0.5, 0.5]) for (let k = 0; k < n; k++) P.push([r * Math.cos((2 * Math.PI * k) / n), r * Math.sin((2 * Math.PI * k) / n), z]); return hull(P); }
export function antiprism(n) {
  const r = 1 / (2 * Math.sin(Math.PI / n)), h = Math.sqrt(1 - (r * (2 * Math.sin(Math.PI / (2 * n)))) ** 2) / 2, P = [];
  for (let k = 0; k < n; k++) { P.push([r * Math.cos((2 * Math.PI * k) / n), r * Math.sin((2 * Math.PI * k) / n), -h]); P.push([r * Math.cos(((2 * k + 1) * Math.PI) / n), r * Math.sin(((2 * k + 1) * Math.PI) / n), h]); }
  return hull(P);
}
export function pyramid(n) {   // n = 4 or 5: all edges 1 (Johnson solids J1, J2)
  const r = 1 / (2 * Math.sin(Math.PI / n)), h = Math.sqrt(1 - r * r), P = [[0, 0, h * 0.75]];
  for (let k = 0; k < n; k++) P.push([r * Math.cos((2 * Math.PI * k) / n), r * Math.sin((2 * Math.PI * k) / n), -h / 4]);
  return hull(P);
}
export function bipyramid() { const r = 1 / Math.sqrt(3), h = Math.sqrt(1 - r * r); return hull([[0, 0, h], [0, 0, -h], ...[0, 1, 2].map((k) => [r * Math.cos((2 * Math.PI * k) / 3), r * Math.sin((2 * Math.PI * k) / 3), 0])]); }
