// The Wythoff triangle (issue #35), pure. The symmetry group of the tetrahedron, the cube or the icosahedron is made of
// reflections in three mirror planes that cut the sphere into identical triangles. Put a point in one triangle, at
// distances (a, b, c) from its three sides, and reflect it everywhere: the convex hull of the copies is a polyhedron whose
// edges have lengths 2a, 2b, 2c. Equal non-zero distances give a uniform solid: the Platonic and Archimedean solids.
// Keeping only the rotations (a twist) gives the snub solids. Also: the dual (Catalan solids), named solids by face
// counts, and a classification by computed properties. Tested in tests/gallery-wythoff.test.mjs.
const PHI = (1 + Math.sqrt(5)) / 2;
export const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
export const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
export const sub = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
const add = (a, b) => [a[0] + b[0], a[1] + b[1], a[2] + b[2]];
const scale = (a, k) => a.map((x) => x * k);
export const norm = (a) => Math.hypot(a[0], a[1], a[2]);
const unit = (a) => scale(a, 1 / norm(a));

// The fundamental triangle of each family: corners A (vertex axis), B (face axis), C (edge axis) and their orders.
export const FAMILIES = {
  T: { corners: [[1, 1, 1], [1, -1, 1], [1, 0, 0]], orders: [3, 3, 2], names: ['Tétraèdre', 'Tetrahedron'] },
  O: { corners: [[0, 0, 1], [1, 1, 1], [0, 1, 1]], orders: [4, 3, 2], names: ['Cube et octaèdre', 'Cube and octahedron'] },
  I: { corners: [[0, 1, PHI], [PHI / 3, 0, (1 + 2 * PHI) / 3], [0, 0, PHI]], orders: [5, 3, 2], names: ['Icosaèdre et dodécaèdre', 'Icosahedron and dodecahedron'] },
};
const mat = (n) => { const u = unit(n); return [0, 1, 2].map((i) => [0, 1, 2].map((j) => (i === j ? 1 : 0) - 2 * u[i] * u[j])); };
const mul = (A, B) => A.map((r) => [0, 1, 2].map((j) => r[0] * B[0][j] + r[1] * B[1][j] + r[2] * B[2][j]));
export const apply = (M, v) => [dot(M[0], v), dot(M[1], v), dot(M[2], v)];
const det = (M) => dot(M[0], cross(M[1], M[2]));
const key = (M) => M.flat().map((x) => Math.round(x * 1e6)).join(',');
// The mirrors (planes through two corners, normals pointing into the triangle) and the whole group, generated by them.
const cache = new Map();
export function family(id) {
  if (cache.has(id)) return cache.get(id);
  const [A, B, C] = FAMILIES[id].corners.map(unit), into = (n, P) => (dot(n, P) < 0 ? scale(n, -1) : n);
  const mirrors = [into(unit(cross(B, C)), A), into(unit(cross(C, A)), B), into(unit(cross(A, B)), C)];   // opposite A, B, C
  const gens = mirrors.map(mat), group = new Map([[key([[1, 0, 0], [0, 1, 0], [0, 0, 1]]), [[1, 0, 0], [0, 1, 0], [0, 0, 1]]]]);
  let frontier = [...group.values()];
  while (frontier.length) { const next = []; for (const M of frontier) for (const G of gens) { const P = mul(G, M), k = key(P); if (!group.has(k)) { group.set(k, P); next.push(P); } } frontier = next; }
  const all = [...group.values()], out = { id, corners: [A, B, C], mirrors, group: all, rotations: all.filter((M) => det(M) > 0) };
  cache.set(id, out); return out;
}
// The point at distances d = [a, b, c] from the three mirrors (it lies in the triangle when they are all ≥ 0).
export function wythoffPoint(F, d) {
  const M = F.mirrors, D = det(M), inv = [cross(M[1], M[2]), cross(M[2], M[0]), cross(M[0], M[1])].map((r) => scale(r, 1 / D));
  return [0, 1, 2].map((q) => inv[0][q] * d[0] + inv[1][q] * d[1] + inv[2][q] * d[2]);   // solves M·p = d
}
const uniq = (pts, tol = 1e-7) => { const out = []; for (const p of pts) if (!out.some((q) => norm(sub(p, q)) < tol)) out.push(p); return out; };
export const orbit = (F, p, twist = false) => uniq((twist ? F.rotations : F.group).map((M) => apply(M, p)));

// Convex hull of points around the origin, faces merged across coplanar triangles: {verts, faces: [{verts (cycle), normal, d}]}.
export function hull(points) {
  const P = points, n = P.length, eps = 1e-9;
  let tris = [];
  // a first tetrahedron
  let i0 = 0, i1 = 1; for (let i = 1; i < n; i++) if (norm(sub(P[i], P[i0])) > norm(sub(P[i1], P[i0]))) i1 = i;
  let i2 = -1, best = 0; for (let i = 0; i < n; i++) { const a = norm(cross(sub(P[i1], P[i0]), sub(P[i], P[i0]))); if (a > best) { best = a; i2 = i; } }
  let i3 = -1; best = 0; const nn = cross(sub(P[i1], P[i0]), sub(P[i2], P[i0])); for (let i = 0; i < n; i++) { const v = Math.abs(dot(nn, sub(P[i], P[i0]))); if (v > best) { best = v; i3 = i; } }
  const centre = scale(add(add(P[i0], P[i1]), add(P[i2], P[i3])), 0.25);
  const make = (a, b, c) => { let N = cross(sub(P[b], P[a]), sub(P[c], P[a])); if (dot(N, sub(P[a], centre)) < 0) { N = scale(N, -1); [b, c] = [c, b]; } return { v: [a, b, c], n: unit(N), off: dot(unit(N), P[a]) }; };
  tris = [make(i0, i1, i2), make(i0, i1, i3), make(i0, i2, i3), make(i1, i2, i3)];
  for (let i = 0; i < n; i++) {
    if ([i0, i1, i2, i3].includes(i)) continue;
    const seen = tris.filter((t) => dot(t.n, P[i]) - t.off > eps); if (!seen.length) continue;
    const edges = new Map();
    for (const t of seen) for (let k = 0; k < 3; k++) { const a = t.v[k], b = t.v[(k + 1) % 3], back = `${b},${a}`; if (edges.has(back)) edges.delete(back); else edges.set(`${a},${b}`, [a, b]); }
    tris = tris.filter((t) => !seen.includes(t));
    for (const [a, b] of edges.values()) tris.push(make(a, b, i));
  }
  // merge coplanar triangles into polygons
  const groups = new Map();
  for (const t of tris) { const k = [...t.n, t.off].map((x) => Math.round(x * 1e6)).join(','); (groups.get(k) || groups.set(k, []).get(k)).push(t); }
  const used = [...new Set(tris.flatMap((t) => t.v))], map = new Map(used.map((v, k) => [v, k])), verts = used.map((v) => P[v]);
  const faces = [...groups.values()].map((ts) => {
    const ids = [...new Set(ts.flatMap((t) => t.v))].map((v) => map.get(v)), N = ts[0].n, c = scale(ids.reduce((s, k) => add(s, verts[k]), [0, 0, 0]), 1 / ids.length);
    const u = unit(sub(verts[ids[0]], c)), w = cross(N, u), ang = (k) => Math.atan2(dot(sub(verts[k], c), w), dot(sub(verts[k], c), u));
    // keep only the corners of the polygon (drop points in the middle of a side)
    const ring = ids.sort((a, b) => ang(a) - ang(b)), corner = ring.filter((k, i) => { const a = verts[ring[(i - 1 + ring.length) % ring.length]], b = verts[k], cc = verts[ring[(i + 1) % ring.length]]; return norm(cross(sub(b, a), sub(cc, b))) > 1e-9; });
    return { verts: corner, normal: N, d: ts[0].off };
  });
  return finish(verts, faces);
}
function finish(verts, faces) {
  const edges = new Set(); faces.forEach((f) => f.verts.forEach((a, i) => { const b = f.verts[(i + 1) % f.verts.length]; edges.add(a < b ? `${a}-${b}` : `${b}-${a}`); }));
  const E = [...edges].map((e) => e.split('-').map(Number));
  return { verts, faces, edges: E, V: verts.length, E: E.length, F: faces.length };
}
export const wythoff = (id, d, twist = false) => { const F = family(id); return hull(orbit(F, wythoffPoint(F, d), twist)); };

