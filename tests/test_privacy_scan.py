"""Privacy regressions for hidden PDF surfaces, notices and unreadable assets."""
import json
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

import pymupdf
import privacy_scan


class PublicationPrivacyTests(unittest.TestCase):
    def test_pdf_hidden_surfaces_are_inspected_without_returning_values(self):
        private_url = 'https://' + 'docs' + '.google.com/document/d/fixture'
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / 'fixture.pdf'
            with pymupdf.open() as doc:
                page = doc.new_page()
                page.insert_text((40, 40), 'A harmless mathematical example')
                doc.set_metadata({'author': 'fixture', 'subject': private_url})
                doc.set_xml_metadata('<metadata><link>' + private_url + '</link></metadata>')
                page.insert_link({'kind': pymupdf.LINK_URI, 'from': pymupdf.Rect(10, 10, 20, 20), 'uri': private_url})
                annotation = page.add_text_annot((30, 30), private_url)
                annotation.update()
                doc.set_toc([[1, private_url, 1]])
                doc.save(path)
            result = privacy_scan.scan_pdf(path)
            surfaces = {entry['surface'] for entry in result['findings']}
            self.assertTrue({'metadata', 'xmp', 'link', 'annotation', 'outline'} <= surfaces)
            self.assertNotIn(private_url, json.dumps(result))
            self.assertEqual(result['pages'], 1)
            self.assertEqual(result['links'], 1)
            self.assertEqual(result['annotations'], 1)

    def test_clean_pdf_and_web_have_measured_hashes(self):
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder)
            with pymupdf.open() as doc:
                doc.new_page().insert_text((40, 40), 'x squared is nonnegative')
                doc.save(root / 'resource.pdf')
            (root / 'lesson.html').write_text('<p>Explore the parabola.</p>')
            records = privacy_scan.scan(root)['records']
            self.assertEqual(len(records), 2)
            self.assertTrue(all(not r['findings'] and len(r['sha256']) == 64 and r['bytes'] > 0 for r in records))

    def test_pdf_embedded_content_requires_review(self):
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / 'attachment.pdf'
            with pymupdf.open() as doc:
                doc.new_page()
                doc.embfile_add('attachment.txt', b'Needs separate review')
                doc.save(path)
            result = privacy_scan.scan_pdf(path)
            self.assertEqual(result['attachments'], 1)
            self.assertIn('attachment', {r['surface'] for r in result['findings']})

    def test_notices_and_corrupt_files_fail_closed(self):
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder)
            (root / 'bad.pdf').write_bytes(b'not a PDF')
            (root / 'notice.html').write_text('<p>AI-generated original</p>')
            records = privacy_scan.scan(root)['records']
            self.assertTrue(records[0].get('error'))
            self.assertEqual(records[1]['findings'][0]['reasons'], ['visible notice or review status'])

    def test_visible_ai_notices_do_not_require_a_specific_following_noun(self):
        for text in ('AI-generated content', 'AI generated lesson', 'Artificial intelligence-generated notes',
                     'Generated by AI', 'Généré avec intelligence artificielle'):
            with self.subTest(text=text):
                self.assertIn('visible notice or review status', privacy_scan.reasons(text))

    def test_hashed_identity_matching_also_covers_filenames(self):
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder)
            (root / 'private-fixture.html').write_text('Clean content')
            with patch.object(privacy_scan.banned, 'findings', side_effect=lambda text: ['banned phrase'] if 'private-fixture' in text else []):
                self.assertEqual(privacy_scan.scan(root)['records'][0]['findings'][0]['reasons'], ['banned phrase'])


if __name__ == '__main__':
    unittest.main()
